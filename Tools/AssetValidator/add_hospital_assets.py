GLB = "D:/MedSimXR/Assets/SimReady/%s.glb"
d = json.load(io.open(P, encoding='utf-8'))
existing = {i['id']: i for i in d['items']}
items = [i for i in d['items'] if i['id'] in ORIGINAL]
n_skipped = 0
for (id_, name, cat, desc, use, grab, fixed) in NEW:
    if not os.path.exists(GLB % id_):
        n_skipped += 1
        continue
    items.append(existing.get(id_) or {
        "id": id_, "displayName": name, "category": cat, "description": desc, "trainingUse": use,
        "labelText": name.upper() + "\nTraining model - not a medical device specification.",
        "source": "simready", "simreadyId": id_, "sourceNote": NOTE, "clinicalReview": "pending",
        "canGrab": grab, "canInspect": True, "isFixed": fixed})
d['items'] = items
io.open(P, 'w', encoding='utf-8', newline='\n').write(json.dumps(d, indent=2, ensure_ascii=False) + '\n')
print(len(items), 'entries;', n_skipped, 'catalogue entries skipped (model not converted yet)')
